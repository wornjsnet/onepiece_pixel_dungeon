package com.shatteredpixel.shatteredpixeldungeon.sprites;

import com.shatteredpixel.shatteredpixeldungeon.Assets;
import com.watabou.noosa.TextureFilm;
import com.watabou.utils.RectF;

import java.util.HashSet;

/**
 * High resolution (32x32) icons, drawn at half scale so they take the same space
 * on screen as normal 16x16 icons while showing twice the detail.
 *
 * An item or talent listed here is drawn from the HD sheets instead of the normal
 * ones. The normal sheets still hold a 16x16 version as a fallback for code that
 * reads them directly. Art is generated by tools/luffy_icons_hd.py.
 */
public class HDIcons {

	public static final int SIZE = 32;
	public static final float SCALE = 0.5f;

	private static final int COLS = 8;

	// *** items: sprites/luffy_items_hd.png ***

	private static final TextureFilm itemFilm = new TextureFilm(COLS*SIZE, SIZE, SIZE, SIZE);
	private static final HashSet<Integer> items = new HashSet<>();

	static {
		//slot in the HD sheet, then the packed size of the art
		addItem(ItemSpriteSheet.RUBBER_FIST, 0, 27, 29);
	}

	private static void addItem(int image, int slot, int width, int height){
		int x = (slot % COLS) * SIZE;
		int y = (slot / COLS) * SIZE;
		itemFilm.add(image, x, y, x + width, y + height);
		items.add(image);
	}

	public static boolean hasItem(int image){
		return items.contains(image);
	}

	public static String itemTexture(){
		return Assets.Sprites.LUFFY_ITEMS_HD;
	}

	public static RectF itemFrame(int image){
		return itemFilm.get(image);
	}

	//height of the item as it appears on screen
	public static float itemHeight(int image){
		return itemFilm.height(image) * SCALE;
	}

	// *** talents: interfaces/luffy_talents_hd.png, keyed by Talent.icon() ***

	private static final TextureFilm talentFilm = new TextureFilm(COLS*SIZE, SIZE, SIZE, SIZE);
	private static final HashSet<Integer> talents = new HashSet<>();

	static {
		addTalent(192, 0); //big eater
		addTalent(193, 1); //pirate's senses
		addTalent(194, 2); //captain's grit
		addTalent(195, 3); //captain's toughness
	}

	private static void addTalent(int icon, int slot){
		int x = (slot % COLS) * SIZE;
		int y = (slot / COLS) * SIZE;
		talentFilm.add(icon, x, y, x + SIZE, y + SIZE);
		talents.add(icon);
	}

	public static boolean hasTalent(int icon){
		return talents.contains(icon);
	}

	public static String talentTexture(){
		return Assets.Interfaces.LUFFY_TALENTS_HD;
	}

	public static RectF talentFrame(int icon){
		return talentFilm.get(icon);
	}
}
